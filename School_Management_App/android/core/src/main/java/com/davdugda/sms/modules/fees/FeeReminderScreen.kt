/** Due reminders to parents (in-app notification + free WhatsApp link) and monthly fee generation. */
class FeeRemindersViewModel(c: AppContainer) : BaseViewModel(c) {
    var classId by mutableStateOf<Int?>(null)
    var sectionId by mutableStateOf<Int?>(null)
    var month by mutableStateOf(YearMonth.now().toString())
    var reminders by mutableStateOf<List<JsonObject>?>(null)
    var generated by mutableStateOf<JsonElement?>(null)
    fun send() = act {
        val r = api.feeReminders(buildJsonObject { classId?.let { put("class_id", it) }; sectionId?.let { put("section_id", it) } })
        reminders = ((r.data as? JsonArray) ?: ((r.data as? JsonObject)?.get("reminders") as? JsonArray))?.filterIsInstance<JsonObject>() ?: emptyList()
        r.message ?: "Reminders sent to ${reminders?.size ?: 0} parent(s) in the app."
    }
    fun generate() = act {
        val r = api.generateFees(buildJsonObject { classId?.let { put("class_id", it) }; put("month", month) })
        generated = r.data
        r.message ?: "Fees generated for $month."
    }
}

@Composable
fun FeeRemindersScreen(generateOnly: Boolean = false) {
    val vm = screenViewModel { FeeRemindersViewModel(it) }
    val scope = screenViewModel { ClassScope(it) }
    val ctx = LocalContext.current
    val user = LocalUser.current
    MessageEffect(vm)
    ScreenList {
        item { ClassSectionPicker(scope.classes.value, vm.classId, vm.sectionId, allowAll = true) { cl, s -> vm.classId = cl; vm.sectionId = s } }
        if (!generateOnly) item {
            ElevatedCard(Modifier.fillMaxWidth()) {
                Column(Modifier.padding(14.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                    Text("Remind parents with dues", style = MaterialTheme.typography.titleMedium)
                    Text("Every parent with unpaid fees gets a notification in the Parent app. You also get a free WhatsApp link for each, to send from your own phone.",
                        style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                    Button(onClick = { vm.send() }, enabled = !vm.busy) { Icon(Icons.Outlined.NotificationsActive, null); Spacer(Modifier.width(6.dp)); Text("Send reminders") }
                }
            }
        }
        if (user.isAdmin || user.isAccountant) item {
            ElevatedCard(Modifier.fillMaxWidth()) {
                Column(Modifier.padding(14.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                    Text("Generate monthly fees", style = MaterialTheme.typography.titleMedium)
                    Text("Creates invoices from the fee structure (minus concessions, plus transport/hostel fees) for the class chosen above, or all classes.",
                        style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
                    FormField("Month (YYYY-MM)", vm.month, { vm.month = it })
                    FilledTonalButton(onClick = { vm.generate() }, enabled = !vm.busy) { Text("Generate invoices") }
                    vm.generated?.let { JsonResultView(it) }
                }
            }
        }
        if (vm.busy) item { LinearProgressIndicator(Modifier.fillMaxWidth()) }
        vm.reminders?.let { list ->
            item { SectionHeader("${list.size} reminder(s)") }
            items(list) { r ->
                val wa = r.str("whatsapp_url")
                InfoCard(
                    r.str("parent_name") ?: r.str("name") ?: "Parent",
                    subtitle = listOfNotNull(r.str("student_name"), r.str("phone")).joinToString(" · ").ifBlank { null },
                    supporting = r.str("due")?.let { d -> "Due: " + (d.toDoubleOrNull()?.let { rupees(it) } ?: d) } ?: r.str("message"),
                    trailing = { if (wa != null) FilledTonalButton(onClick = { ServerFiles.openUrl(ctx, wa) }) { Text("WhatsApp") } },
                )
            }
        }
    }
}
